export function useSiteT() {
    const page = usePage();
    const locale = computed(() => ((page.props.site_locale as string) === 'ny' ? 'ny' : 'en'));
    const t = (key: Key, vars: Record<string, string | number> = {}) => {
        const text = (locale.value === 'ny' ? ny[key] : undefined) ?? en[key];
        return text.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
    };
    const setLocale = (l: 'en' | 'ny') => router.post(route('site.language'), { locale: l }, { preserveScroll: true, preserveState: false });
    return { t, locale, setLocale };
}

/**
 * Page-local copy: each page keeps its own English and Chichewa strings beside its template.
 * Missing Chichewa entries fall back to English. Chichewa here is an unreviewed draft too.
 */
export function useCopy<T extends Record<string, unknown>>(copy: { en: T; ny: Partial<T> }) {
    const { locale } = useSiteT();
    return computed<T>(() => (locale.value === 'ny' ? { ...copy.en, ...copy.ny } : copy.en));
}
